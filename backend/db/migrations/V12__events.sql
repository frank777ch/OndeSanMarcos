-- V12 · Eventos del campus (charlas, ferias, campeonatos…).
--
-- Cada evento puede ocurrir en un lugar (`place_id`, opcional: un evento virtual no tiene lugar) y
-- llega al asistente como un documento `source_type = 'event'` (ver V13 para la caducidad).
-- Mismo patrón que `places`: id numérico autoincremental y `slug` estable y único.
-- Fechas en `timestamptz`; la aplicación las muestra siempre en hora de Lima (UTC-5, sin horario de verano).
-- Un evento sin `ends_at` se considera terminado al acabar el día de `starts_at` (hora de Lima).

create table if not exists events (
    id                bigint generated by default as identity primary key,
    slug              text not null unique
                          check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    title             text not null check (title <> ''),
    description       text,
    image_url         text,
    starts_at         timestamptz not null,
    ends_at           timestamptz,
    place_id          bigint references places (id),
    location_detail   text,
    category          text not null default 'otro'
                          check (category in ('academico', 'cultural', 'deportivo', 'feria',
                                              'charla', 'taller', 'institucional', 'otro')),
    organizer         text,
    status            text not null default 'scheduled'
                          check (status in ('scheduled', 'cancelled', 'postponed')),
    status_note       text,
    is_free           boolean,
    price_note        text,
    audience          text,
    registration_url  text,
    registration_note text,
    modality          text not null default 'in_person'
                          check (modality in ('in_person', 'online', 'hybrid')),
    online_url        text,
    agenda            text[] not null default '{}',
    keywords          text[] not null default '{}',
    website           text,
    email             text,
    phone             text,
    is_published      boolean not null default true,
    created_at        timestamptz not null default now(),
    updated_at        timestamptz not null default now(),
    updated_by        text,
    check (ends_at is null or ends_at >= starts_at)
);

create index if not exists events_starts_idx on events (starts_at);
create index if not exists events_place_idx  on events (place_id);
